"""Bounded skill and proposal-policy RSI; no models or evaluators at import.

This is a PhiAgent adaptation inspired by MetaRSI, not its full reproduction.
Callbacks own remote execution. The controller owns schemas, split isolation,
finite metric validation, matched trials, promotion, and rollback. Local tests
must use synthetic callbacks only, never benchmark cases or evaluator code.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import math
from typing import Callable, Mapping, Sequence

METRICS = ('BLEUScore', 'CLIPScore', 'hsd', 'dyn', 'ndtw')
GATES = ('task_completion', 'entity_identity', 'camera_preservation',
         'motion_continuity', 'visible_action_order')
SPLITS = ('train', 'validation', 'meta_validation', 'test')


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, allow_nan=False).encode()).hexdigest()


def text_hash(value):
    return hashlib.sha256(value.encode()).hexdigest()


def _sha(value):
    if not isinstance(value, str) or len(value) != 64 or any(c not in '0123456789abcdef' for c in value):
        raise ValueError('Expected lowercase SHA-256')
    return value


def _text(value, max_words):
    if not isinstance(value, str) or not value.strip() or len(value.split()) > max_words:
        raise ValueError('Empty or over-budget text')
    return value


@dataclass(frozen=True)
class Partition:
    """Each pair is (source case identity, seed); a case cannot cross splits."""
    name: str
    members: tuple[tuple[str, int], ...]

    def __post_init__(self):
        if self.name not in SPLITS or not self.members or len(set(self.members)) != len(self.members):
            raise ValueError('Invalid or duplicate partition members')
        if any(not isinstance(c, str) or not c or type(s) is not int for c, s in self.members):
            raise ValueError('Require case identifiers and integer seeds')

    @property
    def sha256(self):
        return digest({'split': self.name, 'members': self.members})


@dataclass(frozen=True)
class ScoreCard:
    skill_sha256: str
    partition_sha256: str
    protocol_sha256: str
    evidence_sha256: str
    # Tuples prevent callback-side mutation after the controller accepts a card.
    rows: tuple[tuple[str, int, tuple[float, ...]], ...]

    def means(self, skill, partition, protocol):
        for value in (self.skill_sha256, self.partition_sha256, self.protocol_sha256, self.evidence_sha256):
            _sha(value)
        if (self.skill_sha256 != text_hash(skill) or self.partition_sha256 != partition.sha256
                or self.protocol_sha256 != protocol):
            raise ValueError('Score card has stale skill, split, or evaluator identity')
        keys = [(c, s) for c, s, _ in self.rows]
        if len(keys) != len(set(keys)) or set(keys) != set(partition.members):
            raise ValueError('Require complete, unique case-seed coverage')
        if any(len(v) != len(METRICS) or any(type(x) not in (float, int) or not math.isfinite(x) for x in v)
               for _, _, v in self.rows):
            raise ValueError('Require exactly five finite metrics per output')
        return tuple(sum(v[j] for _, _, v in self.rows) / len(self.rows) for j in range(len(METRICS)))


def dominates(candidate, baseline):
    return all(c >= b for c, b in zip(candidate, baseline)) and any(c > b for c, b in zip(candidate, baseline))


def validate_policy(proposal):
    if not isinstance(proposal, dict) or set(proposal) != {'hypothesis', 'expected_effect', 'risk', 'policy'}:
        raise ValueError('Policy proposals may write only the policy field')
    for key in ('hypothesis', 'expected_effect', 'risk'):
        _text(proposal[key], 100)
    return _text(proposal['policy'], 220)


def validate_patch(proposal):
    if not isinstance(proposal, dict) or set(proposal) != {'hypothesis', 'expected_effect', 'risk', 'edits'}:
        raise ValueError('Skill proposals may write only bounded line edits')
    for key in ('hypothesis', 'expected_effect', 'risk'):
        _text(proposal[key], 100)
    edits = proposal['edits']
    if not isinstance(edits, list) or len(edits) > 2:
        raise ValueError('At most two line edits')
    if any(not isinstance(e, dict) or set(e) != {'old', 'new'} or
           not all(isinstance(v, str) for v in e.values()) for e in edits):
        raise ValueError('Invalid edit schema')
    return edits


class MetaRSI:
    """Every term compares one child from each policy, from identical parents.

    The proposed policy sees training observations and training-history records.
    It never receives validation metrics or validation/test case identifiers.
    Fixed validation decides promotion; callbacks are trusted runtime components,
    not arbitrary programs generated by the proposal model.
    """
    def __init__(self, partitions: Sequence[Partition], protocol_sha256: str, *,
                 observe: Callable, propose_policy: Callable, propose_skill: Callable,
                 apply_patch: Callable, evaluate: Callable, record: Callable):
        self.parts = {p.name: p for p in partitions}
        if len(partitions) != 4 or set(self.parts) != set(SPLITS):
            raise ValueError('Require all four named partitions')
        assigned = {}
        for p in partitions:
            for case, _ in p.members:
                if case in assigned and assigned[case] != p.name:
                    raise ValueError('All seeds of a source case must stay in one partition')
                assigned[case] = p.name
        self.case_ids = frozenset(assigned)
        self.protocol = _sha(protocol_sha256)
        self.observe, self.propose_policy, self.propose_skill = observe, propose_policy, propose_skill
        self.apply_patch, self.evaluate, self.record = apply_patch, evaluate, record

    def _writable_text(self, value):
        if any(case in value for case in self.case_ids):
            raise ValueError("Case identities cannot be stored in a reusable policy or skill")
        return value

    def _measure(self, skill, split, stage):
        if split not in ('validation', 'meta_validation'):
            raise ValueError('Final-test scoring is outside the adaptation controller')
        card = self.evaluate(skill, self.parts[split], stage)
        means = card.means(skill, self.parts[split], self.protocol)
        self.record(stage, {'skill_sha256': text_hash(skill), 'partition_sha256': self.parts[split].sha256,
                            'protocol_sha256': self.protocol, 'evidence_sha256': card.evidence_sha256,
                            'means': dict(zip(METRICS, means))})
        return means

    def _observe(self, skill, stage):
        part = self.parts['train']
        records = self.observe(skill, part, stage)
        if len(records) != len(part.members):
            raise ValueError('Incomplete training observations')
        seen = set()
        for r in records:
            if set(r) != {'case_id', 'seed', 'skill_sha256', 'video_sha256', 'gates', 'trace'}:
                raise ValueError('Training compiler emitted an undeclared field')
            key = (r['case_id'], r['seed'])
            if key not in part.members or key in seen or r['skill_sha256'] != text_hash(skill):
                raise ValueError('Stale, duplicate, or out-of-split training record')
            seen.add(key); _sha(r['video_sha256']); _text(r['trace'], 2000)
            if set(r['gates']) != set(GATES) or any(v not in ('PASS', 'FAIL', 'UNKNOWN') for v in r['gates'].values()):
                raise ValueError('Invalid visible-check record')
        return records

    def run(self, skill, policy, *, terms=2):
        if type(terms) is not int or not 1 <= terms <= 8:
            raise ValueError('Freeze a bounded 1..8 term budget')
        self._writable_text(_text(skill, 300)); self._writable_text(_text(policy, 220))
        history = []
        for term in range(terms):
            prefix = f'term-{term + 1:02d}'
            signal = self._observe(skill, prefix + '-train')
            # Clone model inputs so a callback cannot alter protected observations.
            clone = lambda x: json.loads(json.dumps(x))
            context = {'training': signal, 'training_history': history[-2:]}
            self.record(prefix + '-observe', context)
            proposal = self.propose_policy(policy, clone(context), prefix + '-policy')
            self.record(prefix + '-policy-proposal', proposal)
            try:
                new_policy = self._writable_text(validate_policy(proposal))
                policy_valid = True
            except (ValueError, TypeError) as exc:
                new_policy = policy; policy_valid = False
                self.record(prefix + '-policy-rejected', {'error': str(exc)})
            base_in = self._measure(skill, 'validation', prefix + '-baseline-inner')
            base_meta = self._measure(skill, 'meta_validation', prefix + '-baseline-meta')
            children, meta_values = {}, {}
            for name, pi in (('control', policy), ('proposed', new_policy)):
                trial = prefix + '-' + name
                raw = self.propose_skill(pi, skill, clone(signal), trial)
                self.record(trial + '-proposal', raw)
                try:
                    patch = validate_patch(raw)
                    candidate = self.apply_patch(skill, patch)
                    self._writable_text(_text(candidate, 300))
                except (ValueError, TypeError, KeyError) as exc:
                    self.record(trial + '-rejected', {'error': str(exc)})
                    candidate = skill
                inner = base_in if candidate == skill else self._measure(candidate, 'validation', trial + '-inner')
                child = candidate if dominates(inner, base_in) else skill
                children[name] = child
                meta_values[name] = base_meta if child == skill else self._measure(child, 'meta_validation', trial + '-meta')
                self.record(trial + '-child', {'parent_sha256': text_hash(skill), 'child_sha256': text_hash(child),
                                             'inner_accepted': child != skill, 'policy_sha256': text_hash(pi)})
            accepted_policy = (policy_valid and new_policy != policy and
                               dominates(meta_values['proposed'], meta_values['control']) and
                               dominates(meta_values['proposed'], base_meta))
            chosen = 'proposed' if accepted_policy else 'control'
            parent_skill, parent_policy = skill, policy
            if dominates(meta_values[chosen], base_meta):
                skill = children[chosen]
            if accepted_policy:
                policy = new_policy
            self.record(prefix + '-export', {'skill': skill, 'policy': policy,
                'parent_skill_sha256': text_hash(parent_skill), 'parent_policy_sha256': text_hash(parent_policy),
                'skill_sha256': text_hash(skill), 'policy_sha256': text_hash(policy),
                'policy_accepted': accepted_policy, 'skill_accepted': skill != parent_skill,
                'protocol_sha256': self.protocol})
            # No validation metrics or cases enter the future proposal context.
            history.append({'skill_sha256': text_hash(parent_skill), 'training': clone(signal)})
        result = {'skill': skill, 'policy': policy, 'terms': terms,
                  'skill_sha256': text_hash(skill), 'policy_sha256': text_hash(policy),
                  'protocol_sha256': self.protocol, 'final_test_evaluated': False}
        self.record('frozen-release', result)
        return result
